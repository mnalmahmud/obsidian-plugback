import * as esbuild from "esbuild";
import { readFileSync } from "node:fs";

const production = process.argv[2] === "production";
const target = ["safari15", "chrome120"];
const seed = esbuild.transformSync(readFileSync("seed/main.js", "utf8"), {
	format: "cjs",
	minify: true,
	legalComments: "none",
	target,
}).code;
const options = {
	banner: { js: "/* Generated by esbuild. Source: src/main.ts */" },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: ["obsidian"],
	define: {
		__SEED_MANIFEST_TEXT__: JSON.stringify(readFileSync("seed/manifest.json", "utf8")),
		__SEED_MAIN_JS_TEXT__: JSON.stringify(seed),
	},
	format: "cjs",
	target,
	outfile: "main.js",
	minify: production,
	sourcemap: production ? false : "inline",
	logLevel: "info",
};
if (production) {
	await esbuild.build(options);
} else {
	const context = await esbuild.context(options);
	await context.watch();
}
